"""Build frontend/src/components/map/indiaStates.ts: India's states as SVG paths (#97).

The Map screen draws states as plain SVG, so it needs no map library or tile server and
works offline. Run this only when the boundaries change.

Source: DataMeet India community, States/Admin2 (https://github.com/datameet/maps), CC BY 4.0.
It follows the Survey of India boundaries, including Ladakh and Telangana. Simplify first:

    npx mapshaper Admin2.shp -simplify 1.5% keep-shapes \
        -o india-states.json format=geojson precision=0.001
    python scripts/build_india_map.py india-states.json
"""

import json
import math
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "frontend/src/components/map/indiaStates.ts"
WIDTH = 1000  # viewBox width; the height follows India's shape
# Equirectangular, with longitudes shrunk by cos(mid latitude) so India isn't stretched
MID_LAT = 23.0
KX = math.cos(math.radians(MID_LAT))


def project(lon: float, lat: float, box: tuple[float, float, float]) -> tuple[float, float]:
    west, north, scale = box
    return (lon - west) * KX * scale, (north - lat) * scale


def rings(geometry: dict) -> list[list[list[float]]]:
    if geometry["type"] == "Polygon":
        return geometry["coordinates"]
    return [ring for poly in geometry["coordinates"] for ring in poly]


def path(geometry: dict, box: tuple[float, float, float]) -> str:
    parts = []
    for ring in rings(geometry):
        pts: list[tuple[int, int]] = []
        for lon, lat in ring:
            x, y = project(lon, lat, box)
            pt = (round(x), round(y))  # whole pixels are plenty at this size
            if not pts or pt != pts[-1]:
                pts.append(pt)
        parts.append("M" + " ".join(f"{x} {y}" for x, y in pts) + "Z")
    return "".join(parts)


def main(src: str) -> None:
    features = json.loads(Path(src).read_text(encoding="utf-8"))["features"]
    lons = [p[0] for f in features for r in rings(f["geometry"]) for p in r]
    lats = [p[1] for f in features for r in rings(f["geometry"]) for p in r]
    west, east, south, north = min(lons), max(lons), min(lats), max(lats)
    scale = WIDTH / ((east - west) * KX)
    box = (west, north, scale)
    height = math.ceil((north - south) * scale)
    states = sorted(
        ((f["properties"]["ST_NM"], path(f["geometry"], box)) for f in features),
        key=lambda s: s[0],
    )
    lines = [
        "// Generated by scripts/build_india_map.py. Do not edit by hand.",
        "// Boundaries: DataMeet India community, States/Admin2 (github.com/datameet/maps),",
        "// CC BY 4.0, following Survey of India boundaries.",
        "",
        f"export const MAP_WIDTH = {WIDTH};",
        f"export const MAP_HEIGHT = {height};",
        "/** Longitude/latitude to viewBox x/y, the same projection the paths were built with. */",
        f"export const PROJECTION = {{ west: {west}, north: {north}, scale: {scale}, kx: {KX} }};",
        "",
        "export const INDIA_STATES: { name: string; d: string }[] = [",
        *(f"  {{ name: {json.dumps(name)}, d: {json.dumps(d)} }}," for name, d in states),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB, {len(states)} states)")


if __name__ == "__main__":
    main(sys.argv[1])
